import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { validateExport } from '../../src/web/state/workspace.js';
import { STORAGE_KEY } from '../../src/web/storage/local-workspace.js';
import { LEGACY_MIGRATION_SETTING } from '../../src/web/storage/workspace-db.js';
test('review, conflict prevention, reload, rejection and real JSON download', async ({ page }, info) => {
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (new URL(r.url()).hostname !== '127.0.0.1') external.push(r.url()); });
  await page.goto('/');
  await page.getByRole('button', { name: 'Analyze Text' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('article')).toHaveCount(3);
  await expect(page.getByText('Do not deploy to production yet.')).toBeVisible();
  const task = page.getByRole('article', { name: 'task card', exact: true });
  await task.getByText('Original evidence · UTF-16 [32, 57)').click();
  await expect(task.locator('mark')).toHaveText('check sandbox credentials');
  await task.getByRole('button', { name: 'Edit', exact: true }).click();
  await task.getByLabel('Title', { exact: true }).fill('Deploy to production');
  await expect(task.getByRole('button', { name: 'Confirm', exact: true })).toBeDisabled();
  await expect(task.getByText(/Prohibited action/)).toBeVisible();
  await task.getByLabel('Title', { exact: true }).fill('Check sandbox credentials');
  await task.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByRole('region', {name:/Saved work sessions/}).getByRole('status')).toHaveText('Saved in this browser (IndexedDB).');
  await page.reload();
  await expect(task.getByText('confirmed', { exact: true })).toBeVisible();
  await task.getByRole('button', { name: 'Edit', exact: true }).click();
  await task.getByLabel('Title', { exact: true }).fill('Check sandbox credentials ');
  await expect(task.getByText('draft', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Export confirmed JSON' })).toBeDisabled();
  await task.getByRole('button', { name: 'Confirm', exact: true }).click();
  await page.getByRole('article', { name: 'calendar card', exact: true }).getByRole('button', { name: 'Reject', exact: true }).click();
  const event = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export confirmed JSON' }).click();
  const download = await event;
  expect(download.suggestedFilename()).toBe('codeswitch-confirmed-workcards.json');
  const path = info.outputPath('confirmed.json'); await download.saveAs(path);
  const doc = JSON.parse(await readFile(path, 'utf8'));
  expect(validateExport(doc)).toBe(true); expect(doc.cards.map((c: { id: string }) => c.id)).toEqual(['card-2']);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.evaluate(async () => (await document.fonts.load('16px \"Noto Sans TC Variable\"', '明天早上九點')).length)).toBeGreaterThan(0);
  await page.screenshot({ path: info.outputPath('workbench.png'), fullPage: true });
  expect(errors).toEqual([]); expect(external).toEqual([]);
});
